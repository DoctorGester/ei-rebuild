"""Comment cleanup (C22, docs/comment-guide.md): counts, the mechanical rewrites, and a ratchet.

  python tools/comments.py stats [PATH...]     per-area (or per-file with --files) counts; --kinds: the removal
                                               pass's candidate kinds (docs/comment-guide.md, "Removal pass")
  python tools/comments.py apply [PATH...]     the mechanical rules on // comments, in place
  python tools/comments.py list  [PATH...]     every comment line that still holds an address or a ticket id
  python tools/comments.py banned [PATH...]    every comment line that holds a banned narration word (x87 names,
                                               stack slots, "the inlined", vtable slot numbers, MFC names; C41)
  python tools/comments.py check [--update]    fails when a file's counts go above config/comment_baseline.csv
  python tools/comments.py samecode [REV]      fails when a file changed since REV (default HEAD) differs in more
                                               than comments and whitespace

Only // comments are touched; code, strings, /* */ blocks (the rdata literal tags /*0073B86C*/ among
them) and generated files are left alone. PATH is a file or folder under src/ (default: all of src/);
`--batch C22x` stands for that batch's files (config/comment_batches.txt).
"""
import csv, os, re, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
BASELINE = os.path.join(ROOT, 'config', 'comment_baseline.csv')

# Comments, strings and character literals in the order the compiler meets them (as srcscan.py).
TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"'
                   r"|'(?:\\(?:x[0-9A-Fa-f]+|[0-7]{1,3}|.)|[^'\\\n])'", re.S)
GENERATED = re.compile(r'Generated by tools/|Do not edit\.')

ADDR = r'00[4-7][0-9A-F]{5}'
ADDR_RX = re.compile(r'\b' + ADDR + r'\b')


def ticket_ids():
    """Ticket ids from docs/tickets.toml, longest first. Two-character ids are left out: they are also
    common names in comments (P1 a point, T2 a time, C0 / C2 byte values, R8 a register)."""
    with open(os.path.join(ROOT, 'docs', 'tickets.toml'), 'rb') as f:
        ids = {t['id'] for t in tomllib.load(f).get('ticket', []) if 'id' in t}
    ids = {i for i in ids if len(i) > 2}
    return sorted(ids, key=len, reverse=True)


TICKET = r'(?:' + '|'.join(map(re.escape, ticket_ids())) + r')'
TICKET_RX = re.compile(r'(?<![\w.])' + TICKET + r'(?![\w])')
REF = r'(?:' + ADDR + r'|' + TICKET + r')'
REFS = REF + r'(?:\s*(?:,|;|/|and|or|\+)\s*' + REF + r')*'
# What the old address headers carried next to the address: the return size, the slot, the convention.
TECH = r'(?:RET(?: n| 0x[0-9A-Fa-f]+| \d+)?|EAX \d+|slot \d+|__\w+|inlined|thunk|' + TICKET + r')'
TECHS = TECH + r'(?:\s*[,;]\s*' + TECH + r')*'

# 1. A comment that is only addresses / ticket ids (with the old header extras): goes.
ONLY_REFS = re.compile(r'^//\s*(?:\d+:\s*)?(?:' + REFS + r')(?:\s*\(' + TECHS + r'\))?\s*[.:;]?\s*$')
# 2. A comment that starts with an address header, "006E3DC0 (RET 4). The name ...": the header goes.
HEAD = re.compile(r'^(//\s*)(?:\d+:\s*)?' + ADDR + r'(?:\s*\(' + TECHS + r'\))?\s*[.:;]\s+(?=\S)')
# 3. A parenthesis holding only addresses / ticket ids, " (0058DAF0)", " (S13)": goes.
PAREN = re.compile(r'\s*\(\s*(?:see\s+)?' + REFS + r'\s*\)')
# 4. Ticket ids at the end or start of a parenthesis with other text: "(..., world_rules.cpp; SV7b6)".
PAREN_TAIL = re.compile(r'\s*[;,]\s*(?:see\s+)?' + TICKET + r'(?:\s*[,/]\s*' + TICKET + r')*(?=\s*\))')
PAREN_HEAD = re.compile(r'(?<=\()\s*' + TICKET + r'(?:\s*[,/]\s*' + TICKET + r')*\s*[;,]\s*')

# Words that narrate the decompilation instead of saying what the code does (C41): x87 instruction names, stack
# slots, "as a dword", "the inlined ...", vtable slot numbers, and in src/game the MFC / STLport operation and class
# names of code that is now std. They stay out of comments; src/lib keeps the ones that name what a helper
# emulates (CString's answers, MFC's CFont) and the x87 layer (lib/crt_x87.cpp) its instruction names.
BANNED_COMMON = re.compile(
    r"\b(?:FCOMP?P?|FUCOMP?P?|FISTP?|FILD|FIDIV|FLD1?|FLDZ|FSTP?|FADDP?|FMULP?|FSUBR?P?|FDIVR?P?|FXCH|FCHS|FABS|"
    r"FNSTSW|FSQRT|ST0)\b|TEST AH|stack slots?|integer moves?"
    r"|\b(?:copied|moved|stored|compared|selected|written) as (?:a |one )?[dq]words?\b|\bas a [dq]word\b"
    r"|\b[Tt]he (?:[\w:]+'s? |[\w:]+' )?inlined\b"
    r"|\bvtable slots?\b|\bvirtual slots?\b"
    r"|\b(?:its|their|the|renderer|input|stream|world's|context's|loader's|helper's|DLL's|connection's|manager's|"
    r"CSpell|CItem|UnitClientSpecific|CFigureManager's) [Ss]lots? [0-9]|\b(?:through|via|calls?) slot [0-9]"
    r"|\([Ss]lots? [0-9]|^//\s*[Ss]lots? [0-9]+(?: [/-] [0-9]+)*[:.]")
BANNED_GAME = re.compile(
    r"\b(?:CList|CPtrList|CObList|CTypedPtrList|CArrays?|CByteArray|CWordArray|CDWordArray|CObArray|CPtrArray|"
    r"CStrings?|RemoveAll|AddHead|RemoveHead|RemoveTail|InsertAt)\b|\bMFC\b")
BANNED_EXEMPT = ('src/lib/crt_x87.cpp',)

HISTORY_RX = re.compile(r'(?i)\b(?:shim|forwarder|ported|rewritten|the hook era|was a |used to |no longer|'
                        r'formerly|previously|registration)\b')
ORIGINAL_RX = re.compile(r'(?i)\bthe original\b|\bgame\.exe\b')


# The removal pass's kinds (docs/comment-guide.md, "Removal pass"), counted by `stats --kinds`. Each is a
# candidate count, not a verdict: the pass reads the comment and decides.
OFFSET_TRAILER = re.compile(r'//\s*\+0x[0-9A-Fa-f]+\b')                      # int x;   // +0x1C ...
OFFSET_MENTION = re.compile(r'\+\s?0x[0-9A-Fa-f]+\b')                        # "... (CUnit +0x334) ..."
SLOT_MENTION = re.compile(r'(?i)\bslots?\s+\d+|\bvtable slot')               # "slot 9", "(vtable slot 2)"
NUMBER_TRAILER = re.compile(r'//\s*~?-?[\d.]+(?:\s*/\s*\d+)?f?(?:\s*:.*)?')   # virtual ...;   // 26   /   0.8f;   // 0.8
RULER_BARE = re.compile(r'//[-=*#_~/ ]{3,}')                                 # // ------------
RULER_ONE_WORD = re.compile(r'//\s*-{2,}\s*[\w:~]+\s*-{2,}\s*')              # // --- Close ---------
REGISTER_RX = re.compile(r'\b(?:ST0|EAX|ECX|EDX|ESI|EDI|EBX|EBP|ESP|AL|RET \d+|RET n|__thiscall|__stdcall|'
                         r'__fastcall|__cdecl|thunk|inlined)\b')
FILE_TRAILER = re.compile(r'//\s*(?:[\w/]+\.(?:h|cpp)|"[^"]*")')              # class X;   // x.h   /   // "CItem"
DECLARATION = re.compile(r'\s*(?:(?:class|struct|union|enum)\b[^{]*;|.*\bClassName\b.*)\s*$')
STALE_RX = re.compile(r"(?i)not (?:yet )?rewritten|not ported|game\.exe's code|still (?:the original|game\.exe)|"
                      r"inside game\.exe|the hook build|hooked\b")
BARE_ORIGINAL = re.compile(r'(?i)(?:as|like) (?:in )?the original(?: does| did| game)?\)?[.;]?\s*$')
LONG_BLOCK = 8          # an own-line block this long is a docs/notes candidate
WRAP = 110


def removal_kinds(text):
    """Counts of the removal pass's candidate kinds in one file (zeros for a generated one)."""
    c = dict.fromkeys(['offset trailers', 'offset mentions', 'slot mentions', 'number trailers', 'rulers',
                       'registers', 'file trailers', 'stale claims', 'bare original', 'long blocks', 'rewrap'], 0)
    if GENERATED.search(text[:600]):
        return c
    block, last_line = [], -2
    blocks = []
    for s, e in line_comments(text):
        line_start = text.rfind('\n', 0, s) + 1
        code = text[line_start:s]
        body = text[s:e].rstrip()
        own = not code.strip()
        if own:
            n = text.count('\n', 0, s)
            if block and n == last_line + 1 and code == block[-1][0]:
                block.append((code, body))
            else:
                if block:
                    blocks.append(block)
                block = [(code, body)]
            last_line = n
        if not own and OFFSET_TRAILER.match(body):
            c['offset trailers'] += 1
        elif OFFSET_MENTION.search(body):
            c['offset mentions'] += 1
        if SLOT_MENTION.search(body):
            c['slot mentions'] += 1
        if not own and NUMBER_TRAILER.fullmatch(body):
            c['number trailers'] += 1
        if own and (RULER_BARE.fullmatch(body) or RULER_ONE_WORD.fullmatch(body)):
            c['rulers'] += 1
        if REGISTER_RX.search(body):
            c['registers'] += 1
        if not own and FILE_TRAILER.fullmatch(body) and DECLARATION.fullmatch(code):
            c['file trailers'] += 1
        if STALE_RX.search(body):
            c['stale claims'] += 1
        if BARE_ORIGINAL.search(body):
            c['bare original'] += 1
    if block:
        blocks.append(block)
    for b in blocks:
        if len(b) >= LONG_BLOCK:
            c['long blocks'] += len(b)
        # Prose blocks only: every line "// text", no rulers, lists or indented lines after the first.
        if len(b) < 2 or not all(re.match(r'// \S', body) for _, body in b) or \
                any(re.match(r'// (?:-{2,}|={2,}|\d+[.)] |[-*] )', body) for _, body in b[1:]):
            continue
        width = WRAP - len(b[0][0]) - 3
        lines, cur = 1, 0
        for w in ' '.join(body[3:] for _, body in b).split():
            if cur and cur + 1 + len(w) > width:
                lines, cur = lines + 1, len(w)
            else:
                cur = cur + 1 + len(w) if cur else len(w)
        c['rewrap'] += max(0, len(b) - lines)
    return c


def sources(paths):
    roots = [os.path.join(ROOT, p) for p in paths] if paths else [SRC]
    for root in roots:
        if os.path.isfile(root):
            yield root
            continue
        for dirpath, _, names in os.walk(root):
            for name in sorted(names):
                if name.endswith(('.cpp', '.h', '.inc', '.hlsl', '.hlsli')):
                    yield os.path.join(dirpath, name)


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, '/')


def read(path):
    with open(path, encoding='utf-8', newline='') as f:
        return f.read()


def line_comments(text):
    """(start, end) of every // comment."""
    return [(m.start(), m.end()) for m in TOKEN.finditer(text) if m.group(0).startswith('//')]


def banned_count(body, path):
    """Banned narration words in one comment (see BANNED_COMMON); `path` is the file's path under the repo, or None."""
    if path in BANNED_EXEMPT or (path and path.startswith('src/standalone/')):
        return 0
    n = len(BANNED_COMMON.findall(body))
    if path is None or path.startswith('src/game/'):
        n += len(BANNED_GAME.findall(body))
    return n


SECTION_RX = re.compile(r'^\s*//\s*(-{2,}|={2,})')


def orphan_blocks(text):
    """Comment blocks at column 0 that describe nothing: the next code line after them closes a namespace (a deleted
    function's or member's comment left behind). Section headers (// ---- ...) are not counted."""
    lines = text.split('\n')
    found, i = [], 0
    while i < len(lines):
        s = lines[i].strip()
        if lines[i].startswith('//') and not SECTION_RX.match(lines[i]) and (i == 0 or '//' not in lines[i - 1]):
            j = i
            while j < len(lines) and lines[j].strip().startswith('//'):
                j += 1
            k = j
            while k < len(lines) and not lines[k].strip():
                k += 1
            if k < len(lines) and lines[k].startswith('}') and (i == 0 or not lines[i - 1].rstrip().endswith('\\')):
                found.append(i + 1)
            i = j
        else:
            i += 1
    return found


def count(text, path=None):
    c = {'comment lines': 0, 'addresses': 0, 'ticket ids': 0, 'original / game.exe': 0, 'history words': 0,
         'banned words': 0, 'orphan comments': 0}
    if GENERATED.search(text[:600]):
        return c
    c['orphan comments'] = len(orphan_blocks(text))
    for s, e in line_comments(text):
        body = text[s:e]
        c['comment lines'] += 1
        c['addresses'] += len(ADDR_RX.findall(body))
        c['ticket ids'] += len(TICKET_RX.findall(body))
        c['original / game.exe'] += len(ORIGINAL_RX.findall(body))
        c['history words'] += len(HISTORY_RX.findall(body))
        c['banned words'] += banned_count(body, path)
    return c


def clean_comment(body, own_line):
    """The comment after the mechanical rules; '' when nothing is left. A comment on its own line
    starts with a capital after its header goes; one after code keeps its case."""
    if ONLY_REFS.match(body):
        return ''
    m = HEAD.match(body)
    if m:
        rest = body[m.end():]
        body = m.group(1) + (rest[:1].upper() if own_line else rest[:1]) + rest[1:]
    body = PAREN.sub('', body)
    body = PAREN_TAIL.sub('', body)
    body = PAREN_HEAD.sub('', body)
    body = re.sub(r'^//\s*[,;]\s*', '// ', body).rstrip()
    if re.fullmatch(r'//\s*[.:;,]?', body):
        return ''
    return body


def apply_text(text):
    if GENERATED.search(text[:600]):
        return text
    out, pos = [], 0
    for s, e in line_comments(text):
        line_start = text.rfind('\n', 0, s) + 1
        new = clean_comment(text[s:e], not text[line_start:s].strip())
        if new == text[s:e]:
            continue
        line_end = text.find('\n', e)
        line_end = len(text) if line_end < 0 else line_end + 1
        if not new and not text[line_start:s].strip():
            # A comment line of its own that is now empty: the whole line goes.
            out.append(text[pos:line_start])
            pos = line_end
        elif not new:
            out.append(text[pos:s].rstrip(' \t'))
            pos = e
        else:
            out.append(text[pos:s])
            out.append(new)
            pos = e
    out.append(text[pos:])
    return ''.join(out)


def area(r):
    parts = r.split('/')
    return '/'.join(parts[:2]) if len(parts) > 2 else r


def cmd_stats(paths, per_file, kinds):
    """The counts per area (or file); with `kinds`, the comment lines and the removal pass's kinds."""
    def counts(text):
        c = count(text)
        if kinds:
            c = {'comment lines': c['comment lines'], **removal_kinds(text)}
        return c
    rows = {}
    for p in sources(paths):
        key = rel(p) if per_file else area(rel(p))
        c = counts(read(p))
        acc = rows.setdefault(key, dict.fromkeys(c, 0))
        for k, v in c.items():
            acc[k] += v
    keys = list(counts(''))
    widths = [max(len(k), 7) if kinds else 20 for k in keys]
    print(f'{"":40} ' + ' '.join(f'{k:>{w}}' for k, w in zip(keys, widths)))
    total = dict.fromkeys(keys, 0)
    for key in sorted(rows):
        if per_file and not any(rows[key][k] for k in keys[1:]):
            continue
        print(f'{key:40} ' + ' '.join(f'{rows[key][k]:>{w},}' for k, w in zip(keys, widths)))
        for k in keys:
            total[k] += rows[key][k]
    print(f'{"total":40} ' + ' '.join(f'{total[k]:>{w},}' for k, w in zip(keys, widths)))


def cmd_apply(paths):
    changed = 0
    before = after = 0
    for p in sources(paths):
        text = read(p)
        new = apply_text(text)
        before += count(text)['addresses']
        if new != text:
            after += count(new)['addresses']
            changed += 1
            with open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(new)
        else:
            after += count(text)['addresses']
    print(f'{changed} file(s) changed; addresses in comments {before:,} -> {after:,}')


def cmd_list(paths):
    for p in sources(paths):
        text = read(p)
        if GENERATED.search(text[:600]):
            continue
        for s, e in line_comments(text):
            body = text[s:e]
            if ADDR_RX.search(body) or TICKET_RX.search(body):
                print(f'{rel(p)}:{text.count(chr(10), 0, s) + 1}: {body}')


def cmd_banned(paths):
    """Every comment line that holds a banned narration word."""
    for p in sources(paths):
        text = read(p)
        if GENERATED.search(text[:600]):
            continue
        for s, e in line_comments(text):
            body = text[s:e]
            if banned_count(body, rel(p)):
                print(f'{rel(p)}:{text.count(chr(10), 0, s) + 1}: {body}')


def code_tokens(text):
    """The text without comments, whitespace runs folded: what the compiler sees, line numbers aside."""
    return ' '.join(TOKEN.sub(lambda m: ' ' if m.group(0).startswith('/') else m.group(0), text).split())


def cmd_samecode(rev):
    """Fails when a file changed since `rev` differs in anything but comments and whitespace."""
    import subprocess
    git = lambda *a: subprocess.run(['git', '-C', ROOT, *a], capture_output=True, text=True, encoding='utf-8')
    names = git('diff', '--name-only', rev, '--', 'src').stdout.split()
    bad = 0
    for name in names:
        path = os.path.join(ROOT, name)
        old = git('show', f'{rev}:{name}')
        if old.returncode or not os.path.exists(path):
            print(f'{name}: added or removed')
            bad += 1
        elif code_tokens(old.stdout) != code_tokens(read(path)):
            print(f'{name}: code changed, not only comments')
            bad += 1
    print(f'{len(names)} file(s) changed since {rev}; {bad} with more than comment changes')
    return 1 if bad else 0


RATCHET = ['addresses', 'ticket ids', 'banned words', 'orphan comments']


def cmd_check(update):
    now = {rel(p): count(read(p), rel(p)) for p in sources([])}
    if update:
        base = {}
        if os.path.exists(BASELINE):
            base = {r['file']: r for r in csv.DictReader(open(BASELINE, newline=''))}
        with open(BASELINE, 'w', newline='') as f:
            w = csv.writer(f, lineterminator='\n')
            w.writerow(['file'] + RATCHET)
            for r in sorted(now):
                row = [min(now[r][k], int(base[r].get(k) or 0)) if r in base else now[r][k] for k in RATCHET]
                if base and r not in base:
                    row = [0 for _ in RATCHET]
                if any(row):
                    w.writerow([r] + row)
        print(f'wrote {rel(BASELINE)}')
        return 0
    base = {r['file']: r for r in csv.DictReader(open(BASELINE, newline=''))} if os.path.exists(BASELINE) else {}
    problems = 0
    for r, c in sorted(now.items()):
        for k in RATCHET:
            limit = int(base[r].get(k) or 0) if r in base else 0
            if c[k] > limit:
                problems += 1
                print(f'{r}: {c[k]} {k} in comments (allowed {limit}); see docs/comment-guide.md'
                      + ('; `python tools/comments.py banned` lists them' if k == 'banned words'
                         else '; a comment left by deleted code: delete it with the code' if k == 'orphan comments'
                         else '; `list` shows them'))
    totals = {k: sum(c[k] for c in now.values()) for k in count('')}
    print('comment counts: ' + ', '.join(f'{v:,} {k}' for k, v in totals.items()) + f'; {problems} problem(s)')
    return 1 if problems else 0


def batch_files(ticket):
    """The files of a C22 batch (config/comment_batches.txt) that still exist."""
    files, current = [], None
    for line in open(os.path.join(ROOT, 'config', 'comment_batches.txt'), encoding='utf-8'):
        line = line.split('#')[0].strip()
        if line.startswith('['):
            current = line.strip('[]')
        elif line and current == ticket and os.path.exists(os.path.join(ROOT, line)):
            files.append(line)
    if not files:
        sys.exit(f'no files for batch {ticket} in config/comment_batches.txt')
    return files


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    cmd, rest = argv[0], argv[1:]
    if '--batch' in rest:
        i = rest.index('--batch')
        rest = rest[:i] + batch_files(rest[i + 1]) + rest[i + 2:]
    paths = [a for a in rest if not a.startswith('--')]
    if cmd == 'stats':
        cmd_stats(paths, '--files' in rest, '--kinds' in rest)
    elif cmd == 'apply':
        cmd_apply(paths)
    elif cmd == 'list':
        cmd_list(paths)
    elif cmd == 'banned':
        cmd_banned(paths)
    elif cmd == 'check':
        return cmd_check('--update' in rest)
    elif cmd == 'samecode':
        return cmd_samecode(paths[0] if paths else 'HEAD')
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
