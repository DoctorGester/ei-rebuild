"""Comment cleanup (C22, docs/comment-guide.md): counts, the mechanical rewrites, and a ratchet.

  python tools/comments.py stats [PATH...]     per-area (or per-file with --files) counts
  python tools/comments.py apply [PATH...]     the mechanical rules on // comments, in place
  python tools/comments.py list  [PATH...]     every comment line that still holds an address or a ticket id
  python tools/comments.py check [--update]    fails when a file's counts go above config/comment_baseline.csv
  python tools/comments.py samecode [REV]      fails when a file changed since REV (default HEAD) differs in more
                                               than comments and whitespace

Only // comments are touched; code, strings, /* */ blocks (the rdata literal tags /*0073B86C*/ among
them) and generated files are left alone. PATH is a file or folder under src/ (default: all of src/);
`--batch C22x` stands for that batch's files (config/comment_batches.txt).
"""
import csv, os, re, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
BASELINE = os.path.join(ROOT, 'config', 'comment_baseline.csv')

# Comments, strings and character literals in the order the compiler meets them (as srcscan.py).
TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"'
                   r"|'(?:\\(?:x[0-9A-Fa-f]+|[0-7]{1,3}|.)|[^'\\\n])'", re.S)
GENERATED = re.compile(r'Generated by tools/|Do not edit\.')

ADDR = r'00[4-7][0-9A-F]{5}'
ADDR_RX = re.compile(r'\b' + ADDR + r'\b')


def ticket_ids():
    """Ticket ids from docs/tickets.toml, longest first. Two-character ids with a prefix that is also a
    common name in comments (P1 a point, T2 a time, F3 a field, I1 an index, N2 a normal) are left out."""
    with open(os.path.join(ROOT, 'docs', 'tickets.toml'), 'rb') as f:
        ids = {t['id'] for t in tomllib.load(f).get('ticket', []) if 'id' in t}
    ids = {i for i in ids if not (len(i) == 2 and i[0] in 'PTFIN')}
    return sorted(ids, key=len, reverse=True)


TICKET = r'(?:' + '|'.join(map(re.escape, ticket_ids())) + r')'
TICKET_RX = re.compile(r'(?<![\w.])' + TICKET + r'(?![\w])')
REF = r'(?:' + ADDR + r'|' + TICKET + r')'
REFS = REF + r'(?:\s*(?:,|;|/|and|or|\+)\s*' + REF + r')*'
# What the old address headers carried next to the address: the return size, the slot, the convention.
TECH = r'(?:RET(?: n| 0x[0-9A-Fa-f]+| \d+)?|EAX \d+|slot \d+|__\w+|inlined|thunk|' + TICKET + r')'
TECHS = TECH + r'(?:\s*[,;]\s*' + TECH + r')*'

# 1. A comment that is only addresses / ticket ids (with the old header extras): goes.
ONLY_REFS = re.compile(r'^//\s*(?:\d+:\s*)?(?:' + REFS + r')(?:\s*\(' + TECHS + r'\))?\s*[.:;]?\s*$')
# 2. A comment that starts with an address header, "006E3DC0 (RET 4). The name ...": the header goes.
HEAD = re.compile(r'^(//\s*)(?:\d+:\s*)?' + ADDR + r'(?:\s*\(' + TECHS + r'\))?\s*[.:;]\s+(?=\S)')
# 3. A parenthesis holding only addresses / ticket ids, " (0058DAF0)", " (S13)": goes.
PAREN = re.compile(r'\s*\(\s*(?:see\s+)?' + REFS + r'\s*\)')
# 4. Ticket ids at the end or start of a parenthesis with other text: "(..., world_rules.cpp; SV7b6)".
PAREN_TAIL = re.compile(r'\s*[;,]\s*(?:see\s+)?' + TICKET + r'(?:\s*[,/]\s*' + TICKET + r')*(?=\s*\))')
PAREN_HEAD = re.compile(r'(?<=\()\s*' + TICKET + r'(?:\s*[,/]\s*' + TICKET + r')*\s*[;,]\s*')

HISTORY_RX = re.compile(r'(?i)\b(?:shim|forwarder|ported|rewritten|the hook era|was a |used to |no longer|'
                        r'formerly|previously|registration)\b')
ORIGINAL_RX = re.compile(r'(?i)\bthe original\b|\bgame\.exe\b')


def sources(paths):
    roots = [os.path.join(ROOT, p) for p in paths] if paths else [SRC]
    for root in roots:
        if os.path.isfile(root):
            yield root
            continue
        for dirpath, _, names in os.walk(root):
            for name in sorted(names):
                if name.endswith(('.cpp', '.h', '.inc', '.hlsl', '.hlsli')):
                    yield os.path.join(dirpath, name)


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, '/')


def read(path):
    with open(path, encoding='utf-8', newline='') as f:
        return f.read()


def line_comments(text):
    """(start, end) of every // comment."""
    return [(m.start(), m.end()) for m in TOKEN.finditer(text) if m.group(0).startswith('//')]


def count(text):
    c = {'comment lines': 0, 'addresses': 0, 'ticket ids': 0, 'original / game.exe': 0, 'history words': 0}
    if GENERATED.search(text[:600]):
        return c
    for s, e in line_comments(text):
        body = text[s:e]
        c['comment lines'] += 1
        c['addresses'] += len(ADDR_RX.findall(body))
        c['ticket ids'] += len(TICKET_RX.findall(body))
        c['original / game.exe'] += len(ORIGINAL_RX.findall(body))
        c['history words'] += len(HISTORY_RX.findall(body))
    return c


def clean_comment(body, own_line):
    """The comment after the mechanical rules; '' when nothing is left. A comment on its own line
    starts with a capital after its header goes; one after code keeps its case."""
    if ONLY_REFS.match(body):
        return ''
    m = HEAD.match(body)
    if m:
        rest = body[m.end():]
        body = m.group(1) + (rest[:1].upper() if own_line else rest[:1]) + rest[1:]
    body = PAREN.sub('', body)
    body = PAREN_TAIL.sub('', body)
    body = PAREN_HEAD.sub('', body)
    body = re.sub(r'^//\s*[,;]\s*', '// ', body).rstrip()
    if re.fullmatch(r'//\s*[.:;,]?', body):
        return ''
    return body


def apply_text(text):
    if GENERATED.search(text[:600]):
        return text
    out, pos = [], 0
    for s, e in line_comments(text):
        line_start = text.rfind('\n', 0, s) + 1
        new = clean_comment(text[s:e], not text[line_start:s].strip())
        if new == text[s:e]:
            continue
        line_end = text.find('\n', e)
        line_end = len(text) if line_end < 0 else line_end + 1
        if not new and not text[line_start:s].strip():
            # A comment line of its own that is now empty: the whole line goes.
            out.append(text[pos:line_start])
            pos = line_end
        elif not new:
            out.append(text[pos:s].rstrip(' \t'))
            pos = e
        else:
            out.append(text[pos:s])
            out.append(new)
            pos = e
    out.append(text[pos:])
    return ''.join(out)


def area(r):
    parts = r.split('/')
    return '/'.join(parts[:2]) if len(parts) > 2 else r


def cmd_stats(paths, per_file):
    rows = {}
    for p in sources(paths):
        key = rel(p) if per_file else area(rel(p))
        c = count(read(p))
        acc = rows.setdefault(key, dict.fromkeys(c, 0))
        for k, v in c.items():
            acc[k] += v
    keys = list(count(''))
    print(f'{"":40} ' + ' '.join(f'{k:>20}' for k in keys))
    total = dict.fromkeys(keys, 0)
    for key in sorted(rows):
        if per_file and not any(rows[key][k] for k in keys[1:]):
            continue
        print(f'{key:40} ' + ' '.join(f'{rows[key][k]:>20,}' for k in keys))
        for k in keys:
            total[k] += rows[key][k]
    print(f'{"total":40} ' + ' '.join(f'{total[k]:>20,}' for k in keys))


def cmd_apply(paths):
    changed = 0
    before = after = 0
    for p in sources(paths):
        text = read(p)
        new = apply_text(text)
        before += count(text)['addresses']
        if new != text:
            after += count(new)['addresses']
            changed += 1
            with open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(new)
        else:
            after += count(text)['addresses']
    print(f'{changed} file(s) changed; addresses in comments {before:,} -> {after:,}')


def cmd_list(paths):
    for p in sources(paths):
        text = read(p)
        if GENERATED.search(text[:600]):
            continue
        for s, e in line_comments(text):
            body = text[s:e]
            if ADDR_RX.search(body) or TICKET_RX.search(body):
                print(f'{rel(p)}:{text.count(chr(10), 0, s) + 1}: {body}')


def code_tokens(text):
    """The text without comments, whitespace runs folded: what the compiler sees, line numbers aside."""
    return ' '.join(TOKEN.sub(lambda m: ' ' if m.group(0).startswith('/') else m.group(0), text).split())


def cmd_samecode(rev):
    """Fails when a file changed since `rev` differs in anything but comments and whitespace."""
    import subprocess
    git = lambda *a: subprocess.run(['git', '-C', ROOT, *a], capture_output=True, text=True, encoding='utf-8')
    names = git('diff', '--name-only', rev, '--', 'src').stdout.split()
    bad = 0
    for name in names:
        path = os.path.join(ROOT, name)
        old = git('show', f'{rev}:{name}')
        if old.returncode or not os.path.exists(path):
            print(f'{name}: added or removed')
            bad += 1
        elif code_tokens(old.stdout) != code_tokens(read(path)):
            print(f'{name}: code changed, not only comments')
            bad += 1
    print(f'{len(names)} file(s) changed since {rev}; {bad} with more than comment changes')
    return 1 if bad else 0


RATCHET = ['addresses', 'ticket ids']


def cmd_check(update):
    now = {rel(p): count(read(p)) for p in sources([])}
    if update:
        base = {}
        if os.path.exists(BASELINE):
            base = {r['file']: r for r in csv.DictReader(open(BASELINE, newline=''))}
        with open(BASELINE, 'w', newline='') as f:
            w = csv.writer(f, lineterminator='\n')
            w.writerow(['file'] + RATCHET)
            for r in sorted(now):
                row = [min(now[r][k], int(base[r][k])) if r in base else now[r][k] for k in RATCHET]
                if base and r not in base:
                    row = [0 for _ in RATCHET]
                if any(row):
                    w.writerow([r] + row)
        print(f'wrote {rel(BASELINE)}')
        return 0
    base = {r['file']: r for r in csv.DictReader(open(BASELINE, newline=''))} if os.path.exists(BASELINE) else {}
    problems = 0
    for r, c in sorted(now.items()):
        for k in RATCHET:
            limit = int(base[r][k]) if r in base else 0
            if c[k] > limit:
                problems += 1
                print(f'{r}: {c[k]} {k} in comments (allowed {limit}); see docs/comment-guide.md')
    totals = {k: sum(c[k] for c in now.values()) for k in count('')}
    print('comment counts: ' + ', '.join(f'{v:,} {k}' for k, v in totals.items()) + f'; {problems} problem(s)')
    return 1 if problems else 0


def batch_files(ticket):
    """The files of a C22 batch (config/comment_batches.txt) that still exist."""
    files, current = [], None
    for line in open(os.path.join(ROOT, 'config', 'comment_batches.txt'), encoding='utf-8'):
        line = line.split('#')[0].strip()
        if line.startswith('['):
            current = line.strip('[]')
        elif line and current == ticket and os.path.exists(os.path.join(ROOT, line)):
            files.append(line)
    if not files:
        sys.exit(f'no files for batch {ticket} in config/comment_batches.txt')
    return files


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    cmd, rest = argv[0], argv[1:]
    if '--batch' in rest:
        i = rest.index('--batch')
        rest = rest[:i] + batch_files(rest[i + 1]) + rest[i + 2:]
    paths = [a for a in rest if not a.startswith('--')]
    if cmd == 'stats':
        cmd_stats(paths, '--files' in rest)
    elif cmd == 'apply':
        cmd_apply(paths)
    elif cmd == 'list':
        cmd_list(paths)
    elif cmd == 'check':
        return cmd_check('--update' in rest)
    elif cmd == 'samecode':
        return cmd_samecode(paths[0] if paths else 'HEAD')
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
