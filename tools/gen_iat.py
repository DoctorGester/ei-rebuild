"""Writes src/lib/gameapi.h: Windows API functions called through game.exe's own import table.

Rewritten code calls Win32 through these instead of its own imports, so API hooks that other mods
install in the game's import table (IAT) keep working.
"""
import os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.environ.get('EI_EXE', r'F:\games\Evil Islands (Rebirth)\starter\Engine\game.exe')
DLLS = {'KERNEL32.dll', 'USER32.dll', 'GDI32.dll', 'ADVAPI32.dll', 'WINMM.dll', 'SHELL32.dll', 'ole32.dll'}
# Functions whose prototypes differ from the Windows SDK headers we compile against, or that are macros.
SKIP = {'GetVersion', 'InterlockedIncrement', 'InterlockedDecrement'}

def main():
    d = open(EXE, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    opt = pe + 24
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    imp_rva = struct.unpack_from('<I', d, opt + 96 + 8)[0]
    secs = []
    for i in range(nsec):
        so = opt + optsz + 40 * i
        vsz, va, rsz, rptr = struct.unpack_from('<IIII', d, so + 8)
        secs.append((va, max(vsz, rsz), rptr))
    r2o = lambda rva: next(rva - va + rp for va, sz, rp in secs if va <= rva < va + sz)
    cstr = lambda off: d[off:d.index(b'\0', off)].decode()

    lines = []
    p = r2o(imp_rva)
    while True:
        oft, _, _, name, ft = struct.unpack_from('<IIIII', d, p)
        if not name:
            break
        dll = cstr(r2o(name))
        if dll in DLLS:
            i = 0
            while True:
                v = struct.unpack_from('<I', d, r2o(oft) + 4 * i)[0]
                if not v:
                    break
                if not v & 0x80000000:
                    fn = cstr(r2o(v) + 2)
                    if fn not in SKIP:
                        slot = 0x400000 + ft + 4 * i
                        lines.append(f'inline auto& {fn} = *reinterpret_cast<decltype(&::{fn})*>(0x{slot:08X});  // {dll}')
                i += 1
        p += 20

    out = os.path.join(ROOT, 'src', 'lib', 'gameapi.h')
    with open(out, 'w') as f:
        f.write('#pragma once\n\n// Generated by tools/gen_iat.py. Do not edit.\n')
        f.write('// Windows API through game.exe\'s import table, so other mods\' API hooks still apply.\n\n')
        f.write('#include <windows.h>\n#include <mmsystem.h>\n#include <shellapi.h>\n#include <objbase.h>\n\n')
        f.write('#undef GetObject\n\nnamespace gameapi {\n\n')
        f.write('\n'.join(lines))
        f.write('\n\n} // namespace gameapi\n')
    print(f'{len(lines)} functions -> {out}')

if __name__ == '__main__':
    sys.exit(main())
