"""game.exe's imports, from its import directory (docs/notes/standalone.md, "Own data (S18)"):

  src/lib/gameapi.h                  Windows API functions called through game.exe's import slots: rewritten code
                                     calls Win32 through these instead of its own imports, so API hooks that other
                                     mods install in the game's import table keep working (in game.exe), and the
                                     harness's slot routes apply to our code too.
  src/standalone/image_imports.inc   every import slot of game.exe with its DLL and function (or ordinal): the
                                     standalone image's own import table, which ei_hook.dll resolves into its
                                     storage (src/standalone/image_imports.cpp, S18f).

Both reach a slot through the data seam (game/game_data.h): in game.exe the slot itself, in the image our table's.

usage: python tools/gen_iat.py [--check]
  (no option)  write both files
  --check      exit 1 when a file differs from what the import directory gives (build.cmd)
"""
import argparse, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.environ.get('EI_EXE', r'F:\games\Evil Islands (Rebirth)\starter\Engine\game.exe')
GAMEAPI = os.path.join(ROOT, 'src', 'lib', 'gameapi.h')
IMAGE_IMPORTS = os.path.join(ROOT, 'src', 'standalone', 'image_imports.inc')
DLLS = {'KERNEL32.dll', 'USER32.dll', 'GDI32.dll', 'ADVAPI32.dll', 'WINMM.dll', 'SHELL32.dll', 'ole32.dll'}
# Functions whose prototypes differ from the Windows SDK headers we compile against, or that are macros.
SKIP = {'GetVersion', 'InterlockedIncrement', 'InterlockedDecrement'}
# game_data.h's kImportsBegin / kImportsEnd: the import address table, the first 0x820 bytes of .rdata.
IAT_BEGIN, IAT_END = 0x0073B000, 0x0073B820


def imports(exe):
    """[(slot, dll, function or None, ordinal)] in the import directory's order."""
    d = open(exe, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    opt = pe + 24
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    imp_rva = struct.unpack_from('<I', d, opt + 96 + 8)[0]
    secs = []
    for i in range(nsec):
        so = opt + optsz + 40 * i
        vsz, va, rsz, rptr = struct.unpack_from('<IIII', d, so + 8)
        secs.append((va, max(vsz, rsz), rptr))
    r2o = lambda rva: next(rva - va + rp for va, sz, rp in secs if va <= rva < va + sz)
    cstr = lambda off: d[off:d.index(b'\0', off)].decode()
    out = []
    p = r2o(imp_rva)
    while True:
        oft, _, _, name, ft = struct.unpack_from('<IIIII', d, p)
        if not name:
            break
        dll = cstr(r2o(name))
        i = 0
        while True:
            v = struct.unpack_from('<I', d, r2o(oft or ft) + 4 * i)[0]
            if not v:
                break
            slot = 0x400000 + ft + 4 * i
            assert IAT_BEGIN <= slot < IAT_END, hex(slot)
            if v & 0x80000000:
                out.append((slot, dll, None, v & 0xFFFF))
            else:
                out.append((slot, dll, cstr(r2o(v) + 2), 0))
            i += 1
        p += 20
    return out


def gameapi_text(table):
    lines = [f'inline auto& {fn} = ei::GameData<decltype(&::{fn})>(0x{slot:08X});  // {dll}'
             for slot, dll, fn, _ in table if dll in DLLS and fn and fn not in SKIP]
    text = ('#pragma once\n\n// Generated by tools/gen_iat.py. Do not edit.\n'
            '// Windows API through game.exe\'s import table, so other mods\' API hooks still apply.\n\n'
            '// The slots are reached through the data seam (game/game_data.h, S18).\n\n'
            '#include <windows.h>\n#include <mmsystem.h>\n#include <shellapi.h>\n#include <objbase.h>\n'
            '#include "game/game_data.h"\n\n'
            '#undef GetObject\n\nnamespace gameapi {\n\n')
    return text + '\n'.join(lines) + '\n\n} // namespace gameapi\n', len(lines)


def image_imports_text(table):
    lines = ['// Generated by tools/gen_iat.py from game.exe\'s import directory. Do not edit.',
             '// Every import slot of game.exe (its import address table): {slot, DLL, function (nullptr: by ordinal),',
             '// ordinal}, in the directory\'s order. The image resolves them into ei_hook.dll\'s storage',
             '// (src/standalone/image_imports.cpp, S18f).']
    for slot, dll, fn, ordinal in table:
        name = f'"{fn}"' if fn else 'nullptr'
        lines.append(f'{{ei::DataId(0x{slot:08X}), "{dll}", {name}, {ordinal}}},')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    table = imports(EXE)
    gameapi, functions = gameapi_text(table)
    outputs = [(GAMEAPI, gameapi), (IMAGE_IMPORTS, image_imports_text(table))]
    if args.check:
        stale = []
        for path, text in outputs:
            old = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
            if old != text:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print('gen_iat: out of date (rerun python tools/gen_iat.py): ' + ', '.join(stale))
            return 1
        print(f'gen_iat: {len(table)} import slots, {functions} gameapi functions: up to date')
        return 0
    for path, text in outputs:
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    print(f'{functions} functions -> {GAMEAPI}\n{len(table)} import slots -> {IMAGE_IMPORTS}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
