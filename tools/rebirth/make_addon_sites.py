"""Writes tests/verify/addon_sites.inc from config/rebirth_patches.csv: every site addon.dll writes (patch, address,
size), for the harness's addon fix set (tests/verify/harness_addon.h; docs/notes/rebirth.md, "One test profile").

usage: python tools/rebirth/make_addon_sites.py
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    with open(os.path.join(ROOT, 'config', 'rebirth_patches.csv'), encoding='utf-8') as f:
        rows = [r for r in csv.DictReader(f) if r['source'] == 'addon']
    lines = ['// Generated by tools/rebirth/make_addon_sites.py from config/rebirth_patches.csv: every site addon.dll',
             '// writes, {patch, address, size}. Do not edit.']
    for r in rows:
        lines.append(f'{{Patch::{r["patch"]}, 0x{r["site"]}, {int(r["size"])}}},')
    with open(os.path.join(ROOT, 'tests', 'verify', 'addon_sites.inc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(len(rows), 'sites')


if __name__ == '__main__':
    main()
