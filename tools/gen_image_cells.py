"""The pointer cells of game.exe's data that point into a section the standalone image moves (S18b;
docs/notes/standalone.md, "Own data"): writes src/standalone/image_cells.inc, which image_data.cpp
fixes up when it moves the section.

game.exe has no relocations, so the cells are found by a scan: every aligned dword of .rdata and
.data (as the file holds them; the zero-filled tail holds none) whose value lies in the moved
section, less the tails of strings (the dword's bytes up to its first zero printable, and the four
bytes before it too: text that happens to read as an address). Each cell found must be in REVIEWED
below with what it is: a new one (another exe, a scan change) fails until someone has looked at it.

usage: python tools/gen_image_cells.py [--check] [--exe game.exe]
  (no option)  write src/standalone/image_cells.inc
  --check      exit 1 when the file differs from what the scan writes, or a cell has no review (build.cmd)
"""
import argparse, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'standalone', 'image_cells.inc')
EXE = r'F:\games\Evil Islands (Rebirth)\starter\Engine\game.exe'
BASE = 0x00400000

# The data that can hold cells (as the file holds it: .data's raw bytes end at 0079C000), and the moved
# range (tools/data_seam.py's "bss").
SCANNED = [('rdata', 0x0073B000, 0x00783000), ('data', 0x00783000, 0x0079C000)]
MOVED = ('bss', 0x0079BF70, 0x007CD000)   # game_data.h's kBssBegin / kBssEnd

# Each cell with what it is (looked at in game.exe: who reads the cell, what the target holds).
REVIEWED = {
    0x00746C80: "MFC message map entry (ON_REGISTERED_MESSAGE, handler 00706CF4): the message's variable, "
                "set by a static initialiser to RegisterWindowMessageA(\"commctrl_DragListMsg\")",
    0x00797C04: "the CRT's lock table (_locktable): a preallocated critical section (_mtinitlocks 006F0741)",
    0x00797C24: "the CRT's lock table: a preallocated critical section",
    0x00797C34: "the CRT's lock table: a preallocated critical section",
    0x00797C44: "the CRT's lock table: a preallocated critical section",
    0x00798060: "_iob[0] (stdin) _ptr: the static stdin buffer _bufin",
    0x00798068: "_iob[0] (stdin) _base: _bufin",
    0x0079AE24: "__lconv_c (0079AE20) thousands_sep: __lconv_static_null (\"\")",
    0x0079AE28: "__lconv_c grouping: __lconv_static_null",
    0x0079AE2C: "__lconv_c int_curr_symbol: __lconv_static_null",
    0x0079AE30: "__lconv_c currency_symbol: __lconv_static_null",
    0x0079AE34: "__lconv_c mon_decimal_point: __lconv_static_null",
    0x0079AE38: "__lconv_c mon_thousands_sep: __lconv_static_null",
    0x0079AE3C: "__lconv_c mon_grouping: __lconv_static_null",
    0x0079AE40: "__lconv_c positive_sign: __lconv_static_null",
    0x0079AE44: "__lconv_c negative_sign: __lconv_static_null",
}


def image(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    count = struct.unpack_from('<H', d, pe + 6)[0]
    optional = struct.unpack_from('<H', d, pe + 20)[0]
    size = struct.unpack_from('<I', d, pe + 24 + 56)[0]
    img = bytearray(size)
    at = pe + 24 + optional
    for i in range(count):
        vsize, va, rsize, raw = struct.unpack_from('<IIII', d, at + 40 * i + 8)
        n = min(vsize, rsize)
        img[va:va + n] = d[raw:raw + n]
    return img


def printable(bs):
    return all(0x20 <= b < 0x7F or b in (9, 10, 13) or b >= 0xC0 for b in bs)


def string_tail(img, offset):
    word = img[offset:offset + 4]
    text = word.split(b'\0', 1)[0]
    return len(text) > 0 and printable(text) and printable(img[offset - 4:offset])


def scan(img):
    _, lo, hi = MOVED
    cells = []
    for _, begin, end in SCANNED:
        for a in range(begin, end, 4):
            o = a - BASE
            v = struct.unpack_from('<I', img, o)[0]
            if lo <= v <= hi and not string_tail(img, o):
                cells.append((a, v))
    return cells


def render(cells):
    name = MOVED[0]
    lines = [
        '// Generated by tools/gen_image_cells.py from game.exe. Do not edit.',
        '//',
        f"// The pointer cells of game.exe's .rdata and .data that point into its .{name} (S18b): image_data.cpp",
        '// adds the shift to each when the image moves the section. {cell, the address it holds}.',
    ]
    for a, v in cells:
        lines.append(f'{{DataId(0x{a:08X}), DataId(0x{v:08X})}},   // {REVIEWED.get(a, "NOT REVIEWED")}')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--exe', default=EXE)
    a = ap.parse_args()
    cells = scan(image(a.exe))
    problems = [f'gen_image_cells: {c:08X} -> {v:08X} has no review (tools/gen_image_cells.py REVIEWED)'
                for c, v in cells if c not in REVIEWED]
    problems += [f'gen_image_cells: {c:08X} -> {v:08X} is the end of .{MOVED[0]}: a one-past-the-end pointer of '
                 'its last object, or the next section\'s start? decide and review' for c, v in cells if v == MOVED[2]]
    found = {c for c, _ in cells}
    problems += [f'gen_image_cells: reviewed cell {c:08X} is not found by the scan' for c in REVIEWED if c not in found]
    text = render(cells)
    if a.check:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            problems.append(f'gen_image_cells: {os.path.relpath(OUT, ROOT)} is not what the scan writes: '
                            'run python tools/gen_image_cells.py')
        for p in problems:
            print(p)
        print(f'gen_image_cells: {len(cells)} cell(s) into .{MOVED[0]}, {len(problems)} problem(s)')
        return 1 if problems else 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    for p in problems:
        print(p)
    print(f'{len(cells)} cell(s) into .{MOVED[0]} written to {os.path.relpath(OUT, ROOT)}')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
