"""Generates src/hook/rebirth_sites.inc (the hook installer's table of Rebirth patch sites) from
config/rebirth_patches.csv. Run after editing the CSV:

    python tools/gen_rebirth_sites.py
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VARIANT = {
    '': 'kAlways', 'always': 'kAlways', 'nplayers>7': 'kNPlayersOver7', 'pause12': 'kPause12',
    'pause3': 'kPause3', 'newmaster|test': 'kNewMasterOrTest', 'withtest': 'kWithTest', 'never': 'kNever',
}


def main():
    names = []
    for line in open(os.path.join(ROOT, 'include', 'ei', 'rebirth_patches.inc'), encoding='utf-8'):
        if line.startswith('EI_REBIRTH_PATCH('):
            names.append(line[len('EI_REBIRTH_PATCH('):line.index(')')])
    out = ['// Generated by tools/gen_rebirth_sites.py from config/rebirth_patches.csv. Do not edit.']
    count = 0
    with open(os.path.join(ROOT, 'config', 'rebirth_patches.csv'), newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            if row['patch'] not in names:
                raise SystemExit('unknown patch %s (add it to include/ei/rebirth_patches.inc)' % row['patch'])
            source = 'kAddon' if row['source'] == 'addon' else 'kEiPlugin'
            out.append('{Patch::%s, 0x%s, %d, %s, %s},' % (row['patch'], row['site'], int(row['size']), source,
                                                         VARIANT[row['variant']]))
            count += 1
    with open(os.path.join(ROOT, 'src', 'hook', 'rebirth_sites.inc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d sites' % count)


if __name__ == '__main__':
    main()
