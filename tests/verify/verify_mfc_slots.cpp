// Checks for the scalar deleting destructors the exe's vtables point at and the destructors they call
// (src/lib/mfc_slots.cpp, src/game/game_slots.cpp, ticket S6a). All ours only: a destructor leaves
// its class's vtable and, for a list or a map, an empty header (no nodes, no blocks, no table); a
// deleting destructor runs on an object whose vtable has it in slot 1 (slot 0 for the exception
// classes), returns the object and, when it keeps the memory, leaves the destructor's vtable.
#include "verify.h"

